/** Commentaire du plan : tableau par phase, charge de l'équipe, avertissements, et état caché. */
export function renderPlan(state: PlanState, team: TeamMember[] | null, locale: Locale): string {
  const m = messages(locale);
  const { plan } = state;
  const refById = new Map(plan.tasks.map((t, i) => [t.id, taskRef(i)]));
  const issueOf = new Map(state.issues.map((c) => [c.taskId, c.number]));
  const member = (login: string) => team?.find((t) => t.github.toLowerCase() === login.toLowerCase());

  const lines = [PLAN_MARKER, state.applied ? m.applied(plan.tasks.length) : m.proposed(plan.tasks.length), ""];
  if (plan.summary) lines.push(`> ${escape(plan.summary)}`, "");

  for (const phase of new Set(plan.tasks.map((t) => t.phase))) {
    lines.push(`**${escape(phase)}**`, "", m.columns, "|---|---|---|---|---|");
    for (const task of plan.tasks.filter((t) => t.phase === phase)) {
      const issue = issueOf.get(task.id);
      const title = `${task.status === "done" ? "✅ " : ""}${escape(task.title)}${issue ? ` #${issue}` : ""}`;
      const who = task.assignee ? escape(member(task.assignee)?.name ?? task.assignee) : "—";
      const after = task.depends_on.map((id) => refById.get(id)).join(", ");
      lines.push(`| ${refById.get(task.id)} | ${title} | ${who} | ${task.estimated_hours} h | ${after} |`);
    }
    lines.push("");
  }

  if (team) {
    lines.push(m.workload, "", m.workloadColumns, "|---|---|---|");
    for (const t of team) {
      const planned = plan.tasks
        .filter((task) => task.status !== "done" && task.assignee?.toLowerCase() === t.github.toLowerCase())
        .reduce((sum, task) => sum + task.estimated_hours, 0);
      const capacity = capacityOf(t, plan.duration_days);
      const overloaded = capacity !== undefined && planned > capacity ? " ⚠️" : "";
      lines.push(`| ${escape(t.name ?? t.github)} | ${round(planned)} h${overloaded} | ${capacity === undefined ? "—" : `${round(capacity)} h`} |`);
    }
    lines.push("");
  }

  lines.push(...plan.warnings.map((w) => `- ⚠️ ${escape(w)}`));
  if (plan.warnings.length) lines.push("");
  lines.push(state.applied ? m.footerApplied : m.footerProposed, "", encodeState(state));

  const body = lines.join("\n");
  if (body.length > MAX_COMMENT_LENGTH) throw new Error(m.tooLong);
  return body;
}

/** Capacité sur la durée du projet : heures par semaine, ou heures par jour × nombre de jours. */
export function capacityOf(member: TeamMember, days: number | null | undefined): number | undefined {
  if (member.capacity_hours_per_week) return member.capacity_hours_per_week;
  return member.capacity_hours_per_day && days ? member.capacity_hours_per_day * days : undefined;
}

function encodeState(state: PlanState): string {
  return `<!-- taskvibe:data ${Buffer.from(JSON.stringify(state)).toString("base64")} -->`;
}

/** Dernier état caché du commentaire ; null s'il est absent ou invalide. */
export function decodeState(body: string): PlanState | null {
  const last = [...body.matchAll(DATA_PATTERN)].at(-1);
  if (!last) return null;
  try {
    const parsed = PlanStateSchema.safeParse(JSON.parse(Buffer.from(last[1]!, "base64").toString("utf8")));
    return parsed.success ? parsed.data : null;
  } catch {
    return null;
  }
}

/**
 * Texte issu de l'IA ou des utilisateurs, affiché dans un tableau : pas de retour à la ligne ni de « | »,
 * pas de HTML (un faux état caché serait sinon lu), et pas de @mention qui notifierait quelqu'un.
 */
function escape(value: string): string {
  return value.replace(/[\r\n]+/g, " ").replace(/\|/g, "\\|").replace(/</g, "&lt;").replace(/@/g, "@\u200b");
}

const round = (hours: number) => Math.round(hours * 10) / 10;

/** Sépare la description (modifiable sur GitHub) du bloc d'informations ajouté par le bot. */
const META_MARKER = "<!-- taskvibe:meta -->";

export function descriptionFromIssueBody(body: string | null | undefined): string {
  const value = (body ?? "").replace(/\r\n/g, "\n");
  const marker = value.indexOf(META_MARKER);
  return (marker >= 0 ? value.slice(0, marker) : value).trim();
}

export function taskIssueBody(task: StoredTask, epicNumber: number, blockedBy: number[], locale: Locale): string {
  const m = messages(locale);
  const lines = [task.description, "", META_MARKER, "---", `**${m.issueEpic} :** #${epicNumber}`];
  if (task.phase) lines.push(`**${m.issuePhase} :** ${task.phase}`);
  lines.push(`**${m.issueEstimate} :** ${task.estimated_hours} h`);
  if (task.skills.length) lines.push(`**${m.issueSkills} :** ${task.skills.join(", ")}`);
  if (blockedBy.length) lines.push(`**${m.issueBlockedBy} :** ${blockedBy.map((n) => `#${n}`).join(", ")}`);
  lines.push(`**${m.issueWhy} :** ${task.rationale}`, "", `<sub>${m.issueGenerated}</sub>`);
  return lines.join("\n");
}
